"""Run the RIP vs RIP-X benchmark and write JSON, a Markdown report and plots.

    python -m ripx.benchmark --seeds 30 --output results/benchmark
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Any

from ripx.analytics.benchmark import (
    Timeline,
    run_traffic_benchmark,
    run_update_benchmark,
    save_benchmark,
)

_UPDATE_ROWS = [
    ("control_messages", "Control messages (whole run)"),
    ("stable_control_messages", "Control messages (first stable period)"),
    ("link_failure_convergence_rounds", "Convergence after link failure (rounds)"),
    ("link_recovery_convergence_rounds", "Convergence after link recovery (rounds)"),
    ("router_failure_convergence_rounds", "Convergence after router failure (rounds)"),
    ("router_recovery_convergence_rounds", "Convergence after router recovery (rounds)"),
    ("incorrect_rounds", "Rounds with any incorrect route"),
    ("blackhole_pair_rounds", "Black-holed pair-rounds"),
    ("loop_pair_rounds", "Looping pair-rounds"),
    ("stale_pair_rounds", "Stale-route pair-rounds"),
    ("route_changes", "Route changes (churn)"),
]

_TRAFFIC_ROWS = [
    ("delivered_ratio", "Delivered / offered traffic"),
    ("maximum_utilization", "Peak link utilization"),
    ("mean_path_hops", "Mean path length (hops)"),
]


def _cell(stats: dict[str, Any], precision: int) -> str:
    text = f"{stats['mean']:.{precision}f} [{stats['ci95_low']:.{precision}f}, {stats['ci95_high']:.{precision}f}]"
    if stats.get("unconverged_trials"):
        text += f" ({stats['unconverged_trials']} unconverged)"
    return text


def render_report(updates: dict[str, Any], traffic: dict[str, Any]) -> str:
    configurations = list(updates["summary"])
    lines = [
        "# RIP vs RIP-X benchmark",
        "",
        "Generated by `python -m ripx.benchmark`. Every value is measured by the simulator.",
        "Cells show the mean and its 95% confidence interval across seeds. The Δ columns are",
        "paired differences against standard RIP on the same seed; an interval that excludes 0",
        "is a difference this benchmark can distinguish from noise.",
        "",
        "## 1. Update control",
        "",
        f"Random connected topologies with {updates['topology']['routers']} routers "
        f"(edge probability {updates['topology']['edge_probability']}), seeds {updates['seeds'][0]}–{updates['seeds'][-1]} "
        f"({len(updates['seeds'])} trials). After initial convergence the run lasts {updates['timeline']['horizon']} rounds: "
        f"a link fails at round {updates['timeline']['link_failure']} and recovers at {updates['timeline']['link_recovery']}, "
        f"a router fails at {updates['timeline']['router_failure']} and recovers at {updates['timeline']['router_recovery']}. "
        "The failed link and router are chosen per seed so the rest of the network stays connected.",
        "",
        "Configurations:",
        "",
    ]
    for name, config in updates["configurations"].items():
        lines.append(f"- `{name}`: `{config}`")
    lines += ["", "| Metric | " + " | ".join(configurations) + " | " + " | ".join(f"Δ {name}" for name in configurations[1:]) + " |"]
    lines.append("|---" * (1 + 2 * len(configurations) - 1) + "|")
    for key, label in _UPDATE_ROWS:
        cells = [_cell(updates["summary"][name][key], 1) for name in configurations]
        deltas = [_cell(updates["summary"][name][key]["paired_difference_vs_rip"], 1) for name in configurations[1:]]
        lines.append(f"| {label} | " + " | ".join(cells) + " | " + " | ".join(deltas) + " |")

    summary = traffic["summary"]
    lines += [
        "",
        "## 2. Traffic engineering",
        "",
        f"Random connected topologies with {traffic['topology']['routers']} routers "
        f"(edge probability {traffic['topology']['edge_probability']}), link capacities drawn from "
        f"{traffic['topology']['bandwidth_mbps_choices']} Mbps, {traffic['flows_per_trial']} random flows of 20–80 Mbps per trial, "
        f"{len(traffic['seeds'])} trials. `rip` routes by hop count; `ripx` runs the congestion-aware traffic-engineering loop.",
        "",
        "| Metric | rip | ripx | Δ ripx |",
        "|---|---|---|---|",
    ]
    for key, label in _TRAFFIC_ROWS:
        lines.append(
            f"| {label} | {_cell(summary['rip'][key], 3)} | {_cell(summary['ripx'][key], 3)} | "
            f"{_cell(summary['ripx'][key]['paired_difference_vs_rip'], 3)} |"
        )
    lines += [
        f"| Extra control messages for traffic engineering | – | {_cell(summary['ripx']['te_control_messages'], 1)} | |",
        f"| Traffic-engineering epochs run | – | {_cell(summary['ripx']['epochs_run'], 1)} | |",
        "",
        f"RIP-X delivered more traffic than RIP in {summary['ripx']['trials_improved']} of {len(traffic['seeds'])} trials "
        f"and less in {summary['ripx']['trials_worse']}.",
        "",
        "## Caveats",
        "",
        "- Rounds are discrete; one round stands for about five seconds of RFC timers.",
        "- Control messages are never lost, and link failures are detected immediately by both ends.",
        "- Traffic is an accounting model over current routes, not a packet-level simulation.",
        "- Traffic engineering adjusts link costs; the delivered-traffic gain depends on spare capacity existing on alternative paths.",
        "",
    ]
    return "\n".join(lines)


def _plot(updates: dict[str, Any], traffic: dict[str, Any], destination: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    configurations = list(updates["summary"])
    panels = [
        ("control_messages", "Control messages"),
        ("link_failure_convergence_rounds", "Link-failure convergence (rounds)"),
        ("router_failure_convergence_rounds", "Router-failure convergence (rounds)"),
        ("blackhole_pair_rounds", "Black-holed pair-rounds"),
    ]
    figure, axes = plt.subplots(1, len(panels) + 1, figsize=(4.2 * (len(panels) + 1), 4))
    colors = ["#4c78a8", "#9ecae9", "#f2b36b", "#e45756"]
    for axis, (key, title) in zip(axes, panels):
        stats = [updates["summary"][name][key] for name in configurations]
        means = [item["mean"] for item in stats]
        errors = [[item["mean"] - item["ci95_low"] for item in stats], [item["ci95_high"] - item["mean"] for item in stats]]
        axis.bar(configurations, means, yerr=errors, capsize=4, color=colors[: len(configurations)])
        axis.set_title(title, fontsize=10)
        axis.tick_params(axis="x", labelrotation=30, labelsize=8)
        axis.spines[["top", "right"]].set_visible(False)
    axis = axes[-1]
    stats = [traffic["summary"][name]["delivered_ratio"] for name in ("rip", "ripx")]
    axis.bar(
        ["rip", "ripx (TE)"],
        [item["mean"] for item in stats],
        yerr=[[item["mean"] - item["ci95_low"] for item in stats], [item["ci95_high"] - item["mean"] for item in stats]],
        capsize=4,
        color=[colors[0], colors[-1]],
    )
    axis.set_ylim(0, 1)
    axis.set_title("Delivered / offered traffic", fontsize=10)
    axis.spines[["top", "right"]].set_visible(False)
    figure.suptitle("RIP vs RIP-X (means with 95% confidence intervals)")
    figure.tight_layout()
    figure.savefig(destination, dpi=130)
    plt.close(figure)


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description="Benchmark standard RIP against RIP-X.")
    parser.add_argument("--seeds", type=int, default=30, help="number of seeded trials per experiment")
    parser.add_argument("--first-seed", type=int, default=0)
    parser.add_argument("--routers", type=int, default=20, help="routers in the update-control topologies")
    parser.add_argument("--output", type=Path, default=Path("results/benchmark"))
    parser.add_argument("--no-plot", action="store_true")
    arguments = parser.parse_args(argv)
    seeds = list(range(arguments.first_seed, arguments.first_seed + arguments.seeds))

    updates = run_update_benchmark(seeds, routers=arguments.routers, timeline=Timeline())
    traffic = run_traffic_benchmark(seeds)
    arguments.output.mkdir(parents=True, exist_ok=True)
    save_benchmark(updates, arguments.output / "update_control.json")
    save_benchmark(traffic, arguments.output / "traffic_engineering.json")
    report = render_report(updates, traffic)
    (arguments.output / "report.md").write_text(report, encoding="utf-8")
    if not arguments.no_plot:
        _plot(updates, traffic, arguments.output / "benchmark.png")
    print(report)


if __name__ == "__main__":
    main()
